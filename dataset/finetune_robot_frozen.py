"""
Fine-tunes the LOCO baseline YOLOv8m (runs/detect/yolo_runs/loco_full_v3/weights/best.pt,
5 classes) on the SAM3-pseudo-labeled video frames extended with the new
"iw_hub" (AMR) class (dataset/sam3_v6_finetune_robot.yaml, 6 classes,
generated by add_robot_class_to_pseudo.py).

"LoRA-style" / last-layers-only: most of the network is frozen (backbone +
neck, model indices 0-20) via ultralytics' `freeze` argument, leaving only
the last C2f block and the Detect head (indices 21-22) trainable. This is
layer-freezing, not literal low-rank adapters (ultralytics has no built-in
LoRA support for conv nets) -- picked specifically because a prior full
fine-tune on this same small pseudo-labeled bank (see yolov8_v4 in
dataset/results/loco_eval_results.csv) catastrophically forgot the LOCO
classes after 1 epoch. Freezing the backbone/neck keeps the learned LOCO
features fixed; only the classification/regression head adapts to add the
new class.

Usage:
    python finetune_robot_frozen.py
"""

import os

from ultralytics import YOLO

ROOT = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(ROOT)

BASELINE = os.path.join(PROJECT_ROOT, "runs/detect/yolo_runs/loco_full_v3/weights/best.pt")
DATA_YAML = os.path.join(ROOT, "sam3_v6_finetune_robot.yaml")
FREEZE_LAYERS = 21  # freezes model.0..model.20 (backbone + neck); trains model.21 (C2f) + model.22 (Detect)

if __name__ == "__main__":
    model = YOLO(BASELINE)
    model.train(
        data=DATA_YAML,
        epochs=30,
        patience=10,
        batch=-1,
        imgsz=960,
        cls=1.0,
        freeze=FREEZE_LAYERS,
        project=os.path.join(PROJECT_ROOT, "runs/detect/yolo_runs"),
        name="loco_finetune_pseudo_robot_frozen_v1",
        exist_ok=True,
    )
